"""Declarative base and reusable mixins for all ORM models.

Conventions applied across the schema:

* Externally-exposed primary keys are UUIDv4 (``id``).
* All timestamps are stored in UTC (``TIMESTAMP WITH TIME ZONE``); Africa/Accra
  conversion happens only at presentation boundaries (schemas / serializers).
* Soft-deletable entities carry ``deleted_at``; hard deletes are avoided for
  auditable domain data.
* Mutable financial/inventory rows carry an optimistic-concurrency ``version``
  column enforced by SQLAlchemy's ``version_id_col`` machinery.
"""

from __future__ import annotations

import enum
import uuid
from datetime import datetime
from typing import Any, ClassVar

from sqlalchemy import MetaData, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column
from sqlalchemy.types import TIMESTAMP, Uuid


def enum_values(enum_cls: type[enum.Enum]) -> list[str]:
    """Persist a Python enum by its ``value``, not its ``name``.

    SQLAlchemy's ``Enum`` type defaults to binding ``Member.name``
    (``"MONDAY"``), but every PostgreSQL enum type in ``alembic/versions/``
    is created from the lowercase ``Member.value`` (``"monday"``) — which is
    also what the API schemas serialize. Without this, any insert touching an
    enum column fails with ``invalid input value for enum``.

    Pass to every ``Enum(...)`` column as ``values_callable=enum_values``.
    """
    return [member.value for member in enum_cls]


# A fixed naming convention keeps autogenerated Alembic migrations stable and
# gives every constraint a predictable, greppable name.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Project-wide declarative base."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    type_annotation_map: ClassVar[dict[type, Any]] = {
        uuid.UUID: Uuid(as_uuid=True),
    }


class UUIDPrimaryKeyMixin:
    """Adds a UUIDv4 primary key named ``id``."""

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        default=uuid.uuid4,
        server_default=func.gen_random_uuid(),
    )


class TimestampMixin:
    """Adds UTC ``created_at`` / ``updated_at`` timestamps."""

    created_at: Mapped[datetime] = mapped_column(
        TIMESTAMP(timezone=True),
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        TIMESTAMP(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )


class SoftDeleteMixin:
    """Adds a nullable ``deleted_at`` column for soft-deletable entities."""

    deleted_at: Mapped[datetime | None] = mapped_column(
        TIMESTAMP(timezone=True), nullable=True, default=None
    )

    @property
    def is_deleted(self) -> bool:
        return self.deleted_at is not None


class AuditUserMixin:
    """Adds ``created_by`` / ``updated_by`` user references (nullable UUIDs).

    Not declared as a ForeignKey here because the referenced table name
    varies by context (``users.id`` in almost all cases); concrete models
    add the ``ForeignKey`` constraint explicitly when mixing this in.
    """

    created_by: Mapped[uuid.UUID | None] = mapped_column(nullable=True, default=None)
    updated_by: Mapped[uuid.UUID | None] = mapped_column(nullable=True, default=None)


class OptimisticVersionMixin:
    """Adds an integer ``version`` column for optimistic-concurrency control."""

    version: Mapped[int] = mapped_column(nullable=False, default=1, server_default="1")


class UUIDAuditBase(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """Common base for most domain tables: UUID PK + created/updated timestamps."""

    __abstract__ = True
