"""Writes lib/src/phone_patterns.dart: the libphonenumber patterns that clean
up a typed number before parsing, copied out of the `phonenumbers` package
the backend uses, so the Dart side cannot drift through a typo.

Run from TroSky/frontend/packages/trosky_core with the backend's virtualenv:

    ../../../backend/.venv312/Scripts/python.exe tool/phone_patterns.py
"""

from __future__ import annotations

import pathlib
import re

import phonenumbers
import phonenumbers.phonenumberutil as u

PATTERNS = {
    "validStartChar": u._VALID_START_CHAR_PATTERN,
    "unwantedEndChars": u._UNWANTED_END_CHAR_PATTERN,
    "secondNumberStart": u._SECOND_NUMBER_START_PATTERN,
    "plusChars": u._PLUS_CHARS_PATTERN,
    "validAlphaPhone": u._VALID_ALPHA_PHONE_PATTERN,
    "extension": u._EXTN_PATTERN,
    "validPhoneNumber": u._VALID_PHONE_NUMBER_PATTERN,
}


def to_dart_source(pattern: str) -> str:
    # Python's Unicode \w is letters, digits and underscore in any script.
    pattern = pattern.replace("(?u)", "").replace(r"\w", r"\p{L}\p{N}_")
    out = []
    for ch in pattern:
        if ch == "\\":
            out.append("\\\\")
        elif ch == "'":
            out.append("\\'")
        elif ch == "$":
            out.append("\\$")
        elif ord(ch) > 0x7E or ord(ch) < 0x20:
            out.append(f"\\u{{{ord(ch):04X}}}")
        else:
            out.append(ch)
    return "".join(out)


def main() -> None:
    lines = [
        "// GENERATED by tool/phone_patterns.py from the Python `phonenumbers`",
        f"// package {phonenumbers.__version__}, the version the backend uses. Do not",
        "// edit by hand; rerun the script.",
        "",
    ]
    for name, compiled in PATTERNS.items():
        ignore_case = bool(compiled.flags & re.IGNORECASE)
        lines.append(f"final RegExp {name} = RegExp(")
        lines.append(f"  '{to_dart_source(compiled.pattern)}',")
        lines.append("  unicode: true,")
        if ignore_case:
            lines.append("  caseSensitive: false,")
        lines.append(");")
        lines.append("")
    lines.append(f"const int minLengthForNsn = {u._MIN_LENGTH_FOR_NSN};")
    lines.append(f"const int maxInputStringLength = {u._MAX_INPUT_STRING_LENGTH};")
    lines.append(f"const String isdnSubaddress = '{u._RFC3966_ISDN_SUBADDRESS}';")
    lines.append("")
    lines.append("/// Keypad letters, ITU E.161.")
    lines.append("const Map<String, String> alphaMappings = {")
    for letter, digit in sorted(u._ALPHA_MAPPINGS.items()):
        if letter.isascii() and letter.isupper():
            lines.append(f"  '{letter}': '{digit}',")
    lines.append("};")
    out = pathlib.Path(__file__).resolve().parents[1] / "lib" / "src" / "phone_patterns.dart"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
